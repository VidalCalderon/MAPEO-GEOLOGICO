export const CATEGORY_COLORS: Record<string, string> = {
  "Litologia": "rgba(150, 150, 150, 0.6)",
  "Alteracion": "rgba(200, 150, 200, 0.6)",
  "Mineralizacion": "rgba(200, 200, 150, 0.6)",
  "Estructura_Lineas": "rgba(50, 50, 255, 1.0)",
  "Estructura_Puntos": "rgba(255, 50, 50, 1.0)",
  "Point": "rgba(255, 50, 50, 1.0)",
  "LineString": "rgba(50, 50, 255, 1.0)",
};

export const getFeatureColor = (properties: any) => {
  let baseCat = properties.Categoria || "";
  const catLower = baseCat.toLowerCase();
  
  if (baseCat === 'LineString' || catLower.includes('linea') || catLower.includes('línea')) {
    baseCat = 'Estructura_Lineas';
  } else if (baseCat === 'Point' || catLower.includes('punto')) {
    baseCat = 'Estructura_Puntos';
  } else if (catLower.includes('litolog')) {
    baseCat = 'Litologia';
  } else if (catLower.includes('alteraci')) {
    baseCat = 'Alteracion';
  } else if (catLower.includes('mineralizaci')) {
    baseCat = 'Mineralizacion';
  }
  
  // Si el usuario tiene una estructura anidada en EXCEL_COLORS (ej. EXCEL_COLORS['Estructura_Lineas']['Falla'])
  if (baseCat && EXCEL_COLORS[baseCat] && typeof EXCEL_COLORS[baseCat] === 'object') {
    const val = baseCat === "Alteracion" ? properties.MINERAL_1 : properties.TIPO;
    if (val && (EXCEL_COLORS[baseCat] as any)[val]) {
      return (EXCEL_COLORS[baseCat] as any)[val];
    }
  }
  
  // Soporte para la versión antigua de EXCEL_COLORS (plana) donde las llaves son directamente TIPO
  if (properties.MINERAL_1 && EXCEL_COLORS[properties.MINERAL_1] && typeof EXCEL_COLORS[properties.MINERAL_1] === 'string') {
    return EXCEL_COLORS[properties.MINERAL_1] as string;
  }
  if (properties.TIPO && EXCEL_COLORS[properties.TIPO] && typeof EXCEL_COLORS[properties.TIPO] === 'string') {
    return EXCEL_COLORS[properties.TIPO] as string;
  }

  // Fallback por categoria
  if (baseCat && CATEGORY_COLORS[baseCat]) {
    return CATEGORY_COLORS[baseCat];
  }

  return "rgba(255, 100, 50, 0.4)";
};

