export const getFeatureColor = (properties: any) => {
  // Buscar primero por MINERAL_1
  if (properties.MINERAL_1 && EXCEL_COLORS[properties.MINERAL_1]) {
    return EXCEL_COLORS[properties.MINERAL_1];
  }
  // Luego por TIPO
  if (properties.TIPO && EXCEL_COLORS[properties.TIPO]) {
    return EXCEL_COLORS[properties.TIPO];
  }
  
  // Fallback por categoria
  if (properties.Categoria && CATEGORY_COLORS[properties.Categoria]) {
    return CATEGORY_COLORS[properties.Categoria];
  }
  return "rgba(255, 100, 50, 0.4)";
};
